    norm = PowerNorm(gamma=0.4)

    fig, ax = plt.subplots()

    cf = ax.contourf(X2, X1, Z3, levels=filled_levels, cmap='Greys_r',norm=norm)
    cs = ax.contour(X2, X1, Z3, levels=contour_levels, colors='crimson', linewidths=1.1)

    clbls = ax.clabel(cs, inline=False, fontsize=8, fmt='%.2f', colors='crimson')

    plt.setp(clbls, path_effects=[
        PathEffects.withStroke(linewidth=2, foreground="white")
    ])


    # Set log scales
    ax.set_xscale('log')
    ax.set_yscale('log')

    # Set custom ticks
    ax.set_xticks([0.3, 0.5, 1, 2, 5, 10, 20, 50, 100])
    ax.set_yticks([0.3, 0.5, 1, 2, 5, 10, 20])

    # Format ticks to use normal decimal (not scientific notation)
    ax.get_xaxis().set_major_formatter(ScalarFormatter())
    ax.get_yaxis().set_major_formatter(ScalarFormatter())

    ax.tick_params(axis='x', labelsize=9)
    
    # Ensure minor ticks are shown
    ax.minorticks_off()

    # Axis labels and title
    ax.set_xlabel('Period [days]')
    ax.set_ylabel(r'Radius [$R_{\oplus}$]')
    ax.set_title(fr'e={ecc_fixed}, $\omega={omega_fixed}$, M={mass_fixed}')

    # Colorbar with matching contour levels
    cbar = plt.colorbar(cf, ax=ax)
    cbar.set_label('Completeness')
    cbar.set_ticks(contour_levels)

    plt.tight_layout()
    plt.savefig(save_path + f'/completeness/MES_detection_probability_{ecc_fixed}_{omega_fixed}_{mass_fixed}.pdf', dpi=300)
    plt.close(fig)

